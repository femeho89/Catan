public class Kaart {

    private int height;
    private int witdh;
    private String type;

    public Kaart(int height, int witdh, String type) {
        this.height = height;
        this.witdh = witdh;
        this.type = type;
    }

    public int getHeight() {
        return height;
    }

    public int getWitdh() {
        return witdh;
    }
}
